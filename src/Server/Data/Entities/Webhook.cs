using Zenkins.Shared.Tenancy;

namespace Zenkins.Server.Data.Entities;

/// <summary>
/// One inbound Git webhook of a project (card F-017, PRD §3.9): the configuration a `git push` is
/// authenticated and filtered by.
/// <para>
/// <b>The id is the credential-shaped secret of the URL.</b> A git host is configured with
/// <c>POST /webhooks/{Id}</c>; the id carries no organization, project or name, so the endpoint cannot
/// become a project-existence oracle (an unknown, a disabled and another tenant's id are the same plain
/// 404). It is a random <see cref="Guid"/> and is never derived from anything guessable.
/// </para>
/// <para>
/// <b>The secret is shown once.</b> Unlike an organization secret (write-only end to end), a webhook
/// secret must be copied <em>into</em> the git host, so create and rotate return the plaintext exactly
/// once and every later read returns the configured state only. <see cref="SecretCiphertext"/> is
/// Data Protection output bound to the <c>Zenkins.Webhooks.v1</c> purpose; the plaintext is never
/// stored, never logged and never rendered by a page.
/// </para>
/// <para>
/// <b>The webhook never decides where to build.</b> <see cref="BranchFilter"/> selects which pushes are
/// interesting and <see cref="RequiredTags"/> is copied onto the run, but the run's repository always
/// comes from the project: a payload's <c>repository.clone_url</c> is informational only, so a
/// signature-holding sender can never redirect a build to another repository.
/// </para>
/// </summary>
public sealed class Webhook : ITenantOwned
{
    /// <summary>The opaque id the delivery URL carries. Random on purpose (see the class doc).</summary>
    public Guid Id { get; set; } = Guid.NewGuid();

    /// <inheritdoc />
    public Guid OrganizationId { get; set; }

    /// <summary>The project this webhook triggers runs for. Cascade-deleted with it.</summary>
    public Guid ProjectId { get; set; }

    public Project Project { get; set; } = null!;

    /// <summary>
    /// Human-readable name, unique inside the project (enforced by a unique index, not a pre-flight
    /// query). Also the label the settings page lists the webhook by.
    /// </summary>
    public required string Name { get; set; }

    /// <summary>
    /// Data Protection ciphertext of the shared secret (<c>WebhookSecretProtector</c>, purpose
    /// <c>Zenkins.Webhooks.v1</c>). Deliberately no max length: the framework's output grows with the
    /// plaintext and the plaintext is generated by the server, never typed by a user.
    /// </summary>
    public required string SecretCiphertext { get; set; }

    /// <summary>
    /// When the secret was last replaced (rotation). <see langword="null"/> until the first rotation;
    /// the settings page reports "configured / rotated at" and never the value.
    /// </summary>
    public DateTimeOffset? SecretRotatedAt { get; set; }

    /// <summary>
    /// Comma-separated branch patterns: exact names (<c>main</c>) and a trailing <c>*</c> wildcard
    /// (<c>release/*</c>). An empty value means "the project's default branch", resolved at delivery
    /// time so a project's branch move is followed without editing the webhook.
    /// </summary>
    public required string BranchFilter { get; set; }

    /// <summary>
    /// Comma-separated tags copied onto every run this webhook queues (empty means unrestricted), in
    /// the same shape as the manual trigger form's required tags.
    /// </summary>
    public required string RequiredTags { get; set; } = string.Empty;

    /// <summary>
    /// Whether deliveries are accepted. A disabled webhook's URL answers the same 404 an unknown id
    /// does - pausing a webhook must not turn its id into a probe of the project's existence - and the
    /// secret is retained, so re-enabling needs no re-configuration at the git host.
    /// </summary>
    public bool Enabled { get; set; } = true;

    /// <summary>
    /// The Identity user id of the member who created the webhook. Deliberately no foreign key: an
    /// account deletion must not sweep the project's webhooks away (same discipline as runs/secrets).
    /// </summary>
    public required string CreatedByUserId { get; set; }

    /// <summary>
    /// When the last accepted delivery arrived (a duplicate counts: the git host did deliver). Null
    /// until the first delivery; the settings page reports it instead of a delivery log.
    /// </summary>
    public DateTimeOffset? LastDeliveryAt { get; set; }

    /// <summary>
    /// The last delivery's outcome (see <c>WebhookOutcomes</c>), so the settings page can say why a push
    /// did not build (<c>ignored:branch</c>, <c>queued</c>, …) without storing a log.
    /// </summary>
    public string? LastDeliveryOutcome { get; set; }

    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;

    public DateTimeOffset UpdatedAt { get; set; } = DateTimeOffset.UtcNow;
}

/// <summary>
/// The replay-protection record of one accepted delivery (card F-017). One row per <em>distinct</em>
/// delivery of a webhook.
/// <para>
/// <b>The unique index is the replay guard, not a pre-flight query.</b> <c>(WebhookId, DedupeKey)</c> is
/// unique, so ten identical deliveries racing each other cannot all pass a "have I seen this?" check:
/// exactly one insert wins and the nine losers read the winner's row and answer its outcome. That is
/// what makes "ten replays create one run" a database property rather than a timing assumption.
/// </para>
/// <para>
/// <b>Two key shapes, two windows.</b> <c>id:&lt;hash&gt;</c> is the git host's delivery id
/// (<c>X-GitHub-Delivery</c>, <c>X-Gitea-Delivery</c>, <c>X-Gitlab-Event-UUID</c>) and lives for the
/// long TTL (default 7 days); <c>hash:&lt;hash&gt;</c> is the raw body's SHA-256, used when the sender
/// sends no delivery id, and only absorbs a retry storm inside the short window (default 10 minutes).
/// Both key halves are hashed, so no attacker-controlled header text reaches a column or a log.
/// </para>
/// <para>
/// <b>Pruned by a sweeper, not by the request path.</b> A row past its window is stale: the sweeper
/// eventually deletes it, and a delivery that finds one still there CASes its <c>ReceivedAt</c> forward
/// to claim it as new instead of relying on the sweep having run.
/// </para>
/// </summary>
public sealed class WebhookDelivery : ITenantOwned
{
    public Guid Id { get; set; } = Guid.NewGuid();

    /// <inheritdoc />
    public Guid OrganizationId { get; set; }

    /// <summary>The webhook this delivery belongs to. Cascade-deleted with it.</summary>
    public Guid WebhookId { get; set; }

    public Webhook? Webhook { get; set; }

    /// <summary>
    /// The dedupe key: <c>id:</c> or <c>hash:</c> followed by a lower-case hex SHA-256 (see the class
    /// doc). Bounded because it is always a hash, never raw header text.
    /// </summary>
    public required string DedupeKey { get; set; }

    /// <summary>
    /// What the delivery did, in <c>WebhookOutcomes</c>' vocabulary. A duplicate answers this same
    /// value, which is what makes a git host's retry a 202 with the original result rather than an
    /// error.
    /// </summary>
    public required string Outcome { get; set; }

    /// <summary>The run this delivery queued, when it queued one.</summary>
    public Guid? RunId { get; set; }

    /// <summary>
    /// When this key was claimed. The window is measured from here: an id key older than the TTL, or a
    /// body-hash key older than the short window, is stale and a new delivery may claim it forward.
    /// </summary>
    public DateTimeOffset ReceivedAt { get; set; } = DateTimeOffset.UtcNow;

    public DateTimeOffset CreatedAt { get; set; } = DateTimeOffset.UtcNow;

    public DateTimeOffset UpdatedAt { get; set; } = DateTimeOffset.UtcNow;
}
